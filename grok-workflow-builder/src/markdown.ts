import type { NodeKind, WorkflowDoc } from './types'

export function toMarkdown(doc: WorkflowDoc): string {
  const byKind = (k: NodeKind) => doc.nodes.filter((n) => n.kind === k)
  const lines: string[] = []

  lines.push(`# ${doc.name || 'Untitled Workflow'}`)
  lines.push('')
  if (doc.summary.trim()) {
    lines.push(doc.summary.trim())
    lines.push('')
  }
  lines.push(
    `> Generated by Grok Bot Workflow Builder · ${doc.nodes.length} nodes · ${doc.edges.length} connections`,
  )
  lines.push('')

  const sections: Array<{ title: string; kind: NodeKind }> = [
    { title: 'Master Agent', kind: 'master' },
    { title: 'Sub-Agents', kind: 'subagent' },
    { title: 'Channels', kind: 'channel' },
    { title: 'Tools', kind: 'tool' },
    { title: 'Dependencies', kind: 'dependency' },
    { title: 'Manual Approvals', kind: 'approval' },
  ]

  for (const section of sections) {
    const nodes = byKind(section.kind)
    if (nodes.length === 0) continue
    lines.push(`## ${section.title}`)
    lines.push('')
    for (const n of nodes) {
      lines.push(`### ${n.title}`)
      if (n.description.trim()) lines.push(n.description.trim())
      if (n.dependencies.trim()) {
        lines.push('')
        lines.push(`- **Dependencies:** ${n.dependencies.trim()}`)
      }
      if (n.requiresApproval || n.kind === 'approval') {
        lines.push(`- **Manual approval:** required`)
      }
      lines.push('')
    }
  }

  lines.push('## Workflow Graph')
  lines.push('')
  lines.push('```mermaid')
  lines.push('flowchart TD')
  for (const n of doc.nodes) {
    const label = n.title.replace(/"/g, "'")
    const shape =
      n.kind === 'approval'
        ? `{"${label}"}`
        : n.kind === 'dependency'
          ? `[["${label}"]]`
          : n.kind === 'master'
            ? `("${label}")`
            : `["${label}"]`
    lines.push(`  ${n.id}${shape}`)
  }
  for (const e of doc.edges) {
    lines.push(`  ${e.from} --> ${e.to}`)
  }
  lines.push('```')
  lines.push('')

  lines.push('## Connection Table')
  lines.push('')
  lines.push('| From | To |')
  lines.push('| --- | --- |')
  const titleOf = (id: string) =>
    doc.nodes.find((n) => n.id === id)?.title ?? id
  for (const e of doc.edges) {
    lines.push(`| ${titleOf(e.from)} | ${titleOf(e.to)} |`)
  }
  lines.push('')

  lines.push('## Agent SDK Scaffold Hints')
  lines.push('')
  lines.push('- Master → `bot/agent.ts` + `bot/instructions.md`')
  lines.push('- Sub-agents → `bot/subagents/<id>/`')
  lines.push('- Tools → `bot/tools/<name>.ts`')
  lines.push('- Channels → `bot/channels/*.ts`')
  lines.push('- Dependencies → MCP connections / packages listed on each node')
  lines.push('- Manual approvals → gate before side-effecting tools')
  lines.push('')

  return lines.join('\n')
}

export function downloadTextFile(filename: string, contents: string, mime: string) {
  const blob = new Blob([contents], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
}
